export const ALL_FAQ_ITEMS: FaqItem[] = FAQ_CATEGORIES.flatMap((cat) => cat.items);

/**
 * FAQPage 구조화 데이터 (JSON-LD)
 */
export function buildFaqJsonLd() {
  return {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: ALL_FAQ_ITEMS.map((item) => ({
      '@type': 'Question',
      name: item.q,
      acceptedAnswer: {
        '@type': 'Answer',
        text: item.a,
      },
    })),
  };
}
